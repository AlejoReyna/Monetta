// Generates storefront-theme/snippets/monetta-icon.liquid from design-prototype/src/lib/icons.js.
//   node docs/web-redesign/shopify-staging/scripts/port-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..');
const source = readFileSync(path.join(root, 'design-prototype/src/lib/icons.js'), 'utf8');

function block(name) {
  const match = source.match(new RegExp(`const ${name} = \\{([\\s\\S]*?)\\n\\};`));
  const entries = [];
  for (const m of match[1].matchAll(/^\s*(\w+):\s*(?:\n\s*)?'([^']+)',?$/gm)) entries.push([m[1], m[2]]);
  return entries;
}
const filled = block('FILLED');
const stroked = block('STROKED');
if (filled.length < 30 || stroked.length < 5) throw new Error(`icon parse failed: ${filled.length}/${stroked.length}`);

const svg = (inner) => `<svg class="{{ classes }}" viewBox="0 0 24 24" width="{{ size }}" height="{{ size }}" aria-hidden="true" focusable="false">${inner}</svg>`;
const cases = [
  ...filled.map(([n, d]) => `  {%- when '${n}' -%}${svg(`<path fill="currentColor" d="${d}"/>`)}`),
  ...stroked.map(([n, d]) => `  {%- when '${n}' -%}${svg(`<path fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" d="${d}"/>`)}`),
];

writeFileSync(
  path.join(root, 'storefront-theme/snippets/monetta-icon.liquid'),
  `{%- doc -%}
  Inline SVG icon from the approved prototype (design-prototype/src/lib/icons.js).
  Filled paths are Material Icons (Apache 2.0); stroked marks are the drawer's light Material Symbols look.
  Generated by docs/web-redesign/shopify-staging/scripts/port-icons.mjs.

  @param {string} name - Icon name, e.g. 'bag'.
  @param {number} [size] - Pixel size, 24 by default.
  @param {string} [class] - Extra CSS class.
{%- enddoc -%}
{%- liquid
  assign size = size | default: 24
  assign classes = 'icon icon--' | append: name
  if class != blank
    assign classes = classes | append: ' ' | append: class
  endif
-%}
{%- case name -%}
${cases.join('\n')}
{%- endcase -%}
`,
);
console.log(`icons: ${filled.length} filled, ${stroked.length} stroked`);
