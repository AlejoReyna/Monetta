/// Regenerates the bundled offline catalog from its declared public source.
library;

import 'dart:convert';
import 'dart:io';

import 'package:http/http.dart' as http;

const _catalogPath = 'assets/catalog/catalog.json';

Future<void> main() async {
  final file = File(_catalogPath);
  final previous =
      jsonDecode(await file.readAsString()) as Map<String, dynamic>;
  final source = Uri.parse(previous['_source'] as String);
  if (source.scheme != 'https') {
    throw StateError('El origen del catálogo debe usar HTTPS.');
  }

  final client = http.Client();
  try {
    final products = await _fetchPages(client, source, 'products');
    final collectionsUri = source.replace(path: '/collections.json');
    final collections = await _fetchPages(
      client,
      collectionsUri,
      'collections',
    );
    final normalizedProducts = products.map(_normalizeProduct).toList();
    final snapshot = <String, Object?>{
      '_source': source.replace(query: '').toString(),
      '_snapshot': DateTime.now().toUtc().toIso8601String().split('T').first,
      '_note': 'Public catalog snapshot generated by '
          'bin/refresh_catalog_snapshot.dart.',
      'products': normalizedProducts,
      'collections': collections,
    };
    const encoder = JsonEncoder.withIndent('  ');
    await file.writeAsString('${encoder.convert(snapshot)}\n');
    stdout.writeln(
      'Snapshot actualizado: ${normalizedProducts.length} productos, '
      '${collections.length} colecciones.',
    );
  } finally {
    client.close();
  }
}

Future<List<Map<String, dynamic>>> _fetchPages(
  http.Client client,
  Uri endpoint,
  String key,
) async {
  const pageSize = 250;
  final values = <Map<String, dynamic>>[];
  for (var page = 1;; page += 1) {
    final uri = endpoint.replace(
      queryParameters: {'limit': '$pageSize', 'page': '$page'},
    );
    final response = await client.get(uri).timeout(const Duration(seconds: 20));
    if (response.statusCode != 200) {
      throw HttpException('$uri respondió HTTP ${response.statusCode}');
    }
    final body = jsonDecode(response.body) as Map<String, dynamic>;
    final batch = (body[key] as List<dynamic>)
        .map((value) => Map<String, dynamic>.from(value as Map))
        .toList();
    values.addAll(batch);
    if (batch.length < pageSize) return values;
  }
}

Map<String, Object?> _normalizeProduct(Map<String, dynamic> product) => {
      'id': product['id'],
      'title': product['title'],
      'handle': product['handle'],
      'vendor': product['vendor'],
      'product_type': product['product_type'],
      'created_at': product['created_at'],
      'updated_at': product['updated_at'],
      'tags': product['tags'],
      'images': [
        for (final image in product['images'] as List<dynamic>)
          (image as Map)['src'],
      ],
      'variants': [
        for (final value in product['variants'] as List<dynamic>)
          {
            'id': (value as Map)['id'],
            'title': value['title'],
            'price': value['price'],
            'available': value['available'],
            'compare_at_price': value['compare_at_price'],
          },
      ],
    };
